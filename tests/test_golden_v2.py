_LIST_SEG = re.compile(r"^(.*?\b(?:keeps \d+ cards?:|keeps|draws \d+ cards?:|draws|drafts \d+ cards?:|drafts|draft)) (.+)$")


def _opponent_private_names(data: dict[str, Any], me: str, opp: str) -> set[str]:
    private: set[str] = set()
    visible: set[str] = set()
    for pid, pinfo in data["players"].items():
        visible.add(pinfo["corporation"])
        for cards in pinfo["starting_hand"].values():
            (private if pid == opp else visible).update(cards)
    for m in data["moves"]:
        for field in ("card_options", "cards_kept"):
            for pid, cards in (m.get(field) or {}).items():
                (private if pid == opp else visible).update(cards)
        if m.get("card_drafted"):
            (private if m["player_id"] == opp else visible).add(m["card_drafted"])
        if m.get("card_played"):
            visible.add(m["card_played"])
    return private - visible


def _rename_cards(data: dict[str, Any], mapping: dict[str, str]) -> dict[str, Any]:
    out = copy.deepcopy(data)

    def ren(names: list[str]) -> list[str]:
        return [mapping.get(n, n) for n in names]

    for pinfo in out["players"].values():
        for key, cards in pinfo["starting_hand"].items():
            pinfo["starting_hand"][key] = ren(cards)
    for m in out["moves"]:
        for field in ("card_options", "cards_kept"):
            if m.get(field):
                m[field] = {pid: ren(cards) for pid, cards in m[field].items()}
        if m.get("card_drafted"):
            m["card_drafted"] = mapping.get(m["card_drafted"], m["card_drafted"])
        segs = []
        for seg in m["description"].split(" | "):
            hit = _LIST_SEG.match(seg)
            if hit:
                seg = f"{hit.group(1)} " + ", ".join(ren(hit.group(2).split(", ")))
            segs.append(seg)
        m["description"] = " | ".join(segs)
    return out


def test_golden_opponent_private_isolation(registry: CardRegistry) -> None:
    cards = load_card_data()
    for me, opp in ((A, B), (B, A)):
        data = _load(me)
        private = _opponent_private_names(data, me, opp)
        if me == A:
            assert {"Lichen", "Heather", "Fuel Factory", "Earth Office", "Kelp Farming", "Capital", "Pets",
                    "Satellites", "Helion", "Galilean Mining"} <= private
        text = json.dumps(data, ensure_ascii=False)
        pool = [n for n in sorted(cards) if n not in text and cards[n].card_type not in ("corporation", "prelude",
                                                                                         "standard_project")]
        mapping = {}
        for name in sorted(private):
            kind = cards[name].card_type
            if kind in ("corporation", "prelude"):
                repl = next(n for n in sorted(cards) if cards[n].card_type == kind and n not in text
                            and n not in mapping.values() and n != "Beginner Corporation")
            else:
                repl = pool.pop(0)
            mapping[name] = repl
        mutated = _rename_cards(data, mapping)

        base = _reconstruct(data, registry)
        alt = _reconstruct(mutated, registry)
        mine = [_features(d) for d in base.decisions if d.player_id == me]
        mine_alt = [_features(d) for d in alt.decisions if d.player_id == me]
        assert mine and mine == mine_alt
        blob = json.dumps([d.snapshot for d in base.decisions if d.player_id == me]
                          + [d.payload for d in base.decisions if d.player_id == me])
        for name in private:
            assert f'"{name}"' not in blob, name
