def _load(pid: str) -> dict[str, Any]:
    return json.loads((FIXTURE / pid / f"game_{TABLE}_{pid}.json").read_text(encoding="utf-8"))


def _reconstruct(data: dict[str, Any], registry: CardRegistry, **kwargs: Any):
    ev = evaluate_record(data, path=f"{data['player_perspective']}/game_{TABLE}_{data['player_perspective']}.json",
                         card_registry=registry)
    assert ev.setup.passed
    return reconstruct_log_state(data, setup=ev.setup, drafts=ev.drafts, card_registry=registry, **kwargs)


def _decisions(result, pid: str, kind: str) -> list[LogDecision]:
    return [d for d in result.decisions if d.player_id == pid and d.kind == kind]


